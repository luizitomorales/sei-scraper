-- Tabela de staging para dados do SEI/MS
CREATE TABLE STG_MOVIMENTACAO_PROCESSO (
    ID_MOVIMENTACAO NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    NUM_PROCESSO_SEI VARCHAR2(20 CHAR) NOT NULL,
    DT_MOVIMENTACAO TIMESTAMP NOT NULL,
    USUARIO VARCHAR2(255 CHAR),
    DESCRICAO VARCHAR2(4000 CHAR),
    DEPTO_REMETENTE VARCHAR2(255 CHAR),
    DEPTO_DESTINATARIO VARCHAR2(255 CHAR),
    DT_CARGA TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- Tabela resolvida com vínculo à aquisição
CREATE TABLE MOVIMENTACAO_RESOLVIDA (
    ID_MOVIMENTACAO NUMBER PRIMARY KEY,
    COD_AQUISICAO NUMBER NOT NULL,
    DT_MOVIMENTACAO TIMESTAMP NOT NULL,
    USUARIO VARCHAR2(255 CHAR),
    DESCRICAO VARCHAR2(4000 CHAR),
    DEPTO_REMETENTE VARCHAR2(255 CHAR),
    DEPTO_DESTINATARIO VARCHAR2(255 CHAR),
    DT_RESOLUCAO TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (COD_AQUISICAO) REFERENCES MEC_AQUISICAO(COD_AQUISICAO)
);


-- PROCEDURE

INSERT INTO MOVIMENTACAO_RESOLVIDA (
    ID_MOVIMENTACAO,
    COD_AQUISICAO,
    DT_MOVIMENTACAO,
    USUARIO,
    DESCRICAO,
    DEPTO_REMETENTE,
    DEPTO_DESTINATARIO
)
SELECT 
    stg.ID_MOVIMENTACAO,
    ma.COD_AQUISICAO,
    stg.DT_MOVIMENTACAO,
    stg.USUARIO,
    stg.DESCRICAO,
    stg.DEPTO_REMETENTE,
    stg.DEPTO_DESTINATARIO
FROM STG_MOVIMENTACAO_PROCESSO stg
JOIN MEC_AQUISICAO ma
  ON stg.NUM_PROCESSO_SEI = ma.PROCESSO;


--  CRIAÇÃO MICRO_TAREFA 
ALTER TABLE MEC_TAREFA ADD DESC_MICRO_TAREFA VARCHAR (1000 CHAR)


-- Injeção MEVC_TAREFA (AINDA MODELAGEM DIMENSIONAL)

INSERT INTO ORIGINAL.MEC_TAREFA (
    COD_AQUISICAO,
    NOME_ANALISTA,
    DT_ENTRADA,
    DT_SAIDA,
    DESTINO,
    CREATED,
    CREATED_BY,
    UPDATED,
    UPDATED_BY,
    DESC_MICRO_TAREFA
)
SELECT 
    r.COD_AQUISICAO,
    r.USUARIO AS NOME_ANALISTA,
    r.DT_MOVIMENTACAO AS DT_ENTRADA,
    LEAD(r.DT_MOVIMENTACAO) OVER (PARTITION BY r.COD_AQUISICAO ORDER BY r.DT_MOVIMENTACAO) AS DT_SAIDA,
    r.DEPTO_DESTINATARIO AS DESTINO,
    CURRENT_TIMESTAMP AS CREATED,
    r.USUARIO AS CREATED_BY,
    CURRENT_TIMESTAMP AS UPDATED,
    r.USUARIO AS UPDATED_BY,
    (
        SELECT LISTAGG(DESCRICAO, ' | ') WITHIN GROUP (ORDER BY DT_MOVIMENTACAO)
        FROM ORIGINAL.MOVIMENTACAO_RESOLVIDA r2
        WHERE r2.COD_AQUISICAO = r.COD_AQUISICAO
    ) AS DESC_MICRO_TAREFA
FROM ORIGINAL.MOVIMENTACAO_RESOLVIDA r;

-- TABELA FATO

CREATE OR REPLACE VIEW VW_MICROTAREFAS_ANALITICA AS
SELECT
    r.COD_AQUISICAO,
    r.USUARIO,
    LAG(r.DEPTO_DESTINATARIO) OVER (PARTITION BY r.COD_AQUISICAO ORDER BY r.DT_MOVIMENTACAO) AS DEPTO_REMETENTE,
    r.DEPTO_DESTINATARIO,
    r.DT_MOVIMENTACAO AS DT_ENTRADA,
    LEAD(r.DT_MOVIMENTACAO) OVER (PARTITION BY r.COD_AQUISICAO ORDER BY r.DT_MOVIMENTACAO) AS DT_SAIDA,
    LEAD(r.DT_MOVIMENTACAO) OVER (PARTITION BY r.COD_AQUISICAO ORDER BY r.DT_MOVIMENTACAO)
        - r.DT_MOVIMENTACAO AS TEMPO_MICROTAREFA,
    r.DESCRICAO AS DESC_MICRO_TAREFA
FROM MOVIMENTACAO_RESOLVIDA r;

CREATE TABLE FATO_MICROTAREFAS (
    ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    COD_AQUISICAO NUMBER NOT NULL,
    USUARIO VARCHAR2(255),
    DEPTO_REMETENTE VARCHAR2(255),
    DEPTO_DESTINATARIO VARCHAR2(255),
    DT_ENTRADA TIMESTAMP,
    DT_SAIDA TIMESTAMP,
    TEMPO_MICROTAREFA INTERVAL DAY TO SECOND,
    DIAS_UTEIS NUMBER,
    VELOCIDADE_ATUAL NUMBER,
    DESC_MICRO_TAREFA VARCHAR2(4000),
    DT_ATUALIZACAO TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE OR REPLACE PROCEDURE PRC_ATUALIZA_FATO_MICROTAREFAS AS
BEGIN
    -- Limpa dados anteriores (opcional, se for recriar tudo)
    DELETE FROM FATO_MICROTAREFAS;

    -- Insere dados atualizados da view
    INSERT INTO FATO_MICROTAREFAS (
        COD_AQUISICAO,
        USUARIO,
        DEPTO_REMETENTE,
        DEPTO_DESTINATARIO,
        DT_ENTRADA,
        DT_SAIDA,
        TEMPO_MICROTAREFA,
        DIAS_UTEIS,
        VELOCIDADE_ATUAL,
        DESC_MICRO_TAREFA,
        DT_ATUALIZACAO
    )
    SELECT
        COD_AQUISICAO,
        USUARIO,
        DEPTO_REMETENTE,
        DEPTO_DESTINATARIO,
        DT_ENTRADA,
        DT_SAIDA,
        TEMPO_MICROTAREFA,
        -- Cálculo de dias úteis (simplificado: assume 2ª a 6ª como úteis)
        (SELECT COUNT(*) FROM (
            SELECT DT_ENTRADA + LEVEL - 1 AS dia
            FROM DUAL
            CONNECT BY DT_ENTRADA + LEVEL - 1 <= DT_SAIDA
        ) WHERE TO_CHAR(dia, 'D') BETWEEN '2' AND '6') AS DIAS_UTEIS,
        EXTRACT(DAY FROM TEMPO_MICROTAREFA) - EXTRACT(DAY FROM LAG(TEMPO_MICROTAREFA) OVER (
            PARTITION BY COD_AQUISICAO ORDER BY DT_ENTRADA
        )) AS VELOCIDADE_ATUAL,
        DESC_MICRO_TAREFA,
        CURRENT_TIMESTAMP
    FROM VW_MICROTAREFAS_ANALITICA;
END;
