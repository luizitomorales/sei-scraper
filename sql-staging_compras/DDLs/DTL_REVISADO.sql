    END;
  END;
  -------------------------------------------------------------------- Público: INCREMENTAL------------------------------------------------------------------PROCEDURE RUN_INCREMENTAL(p_close_open_intervals BOOLEAN DEFAULT FALSE,
                            p_cutoff_ts           TIMESTAMP DEFAULT SYSTIMESTAMP) IS    v_wm TIMESTAMP := GET_WATERMARK;
