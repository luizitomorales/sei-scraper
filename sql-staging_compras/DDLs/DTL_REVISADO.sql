3.3 Função de dias úteis (recomendada)
Sua contagem usava TO_CHAR(..., 'D'), que depende de NLS e falha com TIMESTAMP. É muito mais seguro ter uma tabela de calendário (com feriados). Aqui vai uma função simples sem feriados, contando seg a sex:
CREATE OR REPLACE FUNCTION ORIGINAL.FN_DIAS_UTEIS(p_dt_ini TIMESTAMP, p_dt_fim TIMESTAMP)RETURN NUMBERIS    v_ini DATE := TRUNC(CAST(p_dt_ini AS DATE));
    v_fim DATE := TRUNC(CAST(p_dt_fim AS DATE));
    v_cnt NUMBER := 0;BEGIN    IF p_dt_fim IS NULL OR p_dt_ini IS NULL THENRETURN NULL;
    END IF;
    IF v_fim < v_ini THENRETURN 0;
    END IF;
    -- percorre dias (para grandes intervalos, troco por fórmula; para microtarefas, costuma ser curto)FOR d IN (
        SELECT v_ini + LEVEL - 1 AS dia
        FROM DUAL
        CONNECT BY v_ini + LEVEL - 1 <= v_fim
    )
    LOOP
        -- 2..6 = Seg..Sex em NLS_TERRITORY=AMERICA; fixamos NLS de forma explícita:        IF TO_CHAR(d.dia, 'D', 'NLS_TERRITORY=AMERICA') BETWEEN '2' AND '6' THEN            v_cnt := v_cnt + 1;
        END IF;
    END LOOP;
    RETURN v_cnt;END;/ 

