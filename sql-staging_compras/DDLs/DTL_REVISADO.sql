CREATE OR REPLACE PACKAGE BODY ORIGINAL.PKG_FATO_MICROTAREFAS AS-------------------------------------------------------------------- Interno: obtém watermark atual------------------------------------------------------------------FUNCTION GET_WATERMARK RETURN TIMESTAMP IS    v_wm TIMESTAMP;
  BEGINSELECT WATERMARK_TS
      INTO v_wm
      FROM ORIGINAL.ETL_CTRL_FATO_MICROTAREFAS
     WHERE ID = (SELECT MAX(ID) FROM ORIGINAL.ETL_CTRL_FATO_MICROTAREFAS);
    RETURN v_wm;
  EXCEPTION WHEN NO_DATA_FOUND THENRETURN TIMESTAMP '1970-01-01 00:00:00';
  END;
  -------------------------------------------------------------------- Interno: atualiza watermark------------------------------------------------------------------PROCEDURE SET_WATERMARK(p_new_wm TIMESTAMP, p_mode VARCHAR2, p_notes VARCHAR2) ISBEGININSERT INTO ORIGINAL.ETL_CTRL_FATO_MICROTAREFAS (WATERMARK_TS, LAST_RUN_TS, MODE, NOTES)
    VALUES (p_new_wm, SYSTIMESTAMP, p_mode, p_notes);
    COMMIT;
  END;
  -------------------------------------------------------------------- Interno: fonte base com regra de "fechamento" de intervalos-- Observação:--  - FULL: considera todos os registros da view--  - INCR: filtra por watermark--  - Se p_close_open_intervals = TRUE, fecha DT_SAIDA NULL com p_cutoff_ts------------------------------------------------------------------FUNCTION SRC_DATA(p_mode VARCHAR2,
                    p_wm   TIMESTAMP,
                    p_close_open_intervals BOOLEAN,
                    p_cutoff_ts TIMESTAMP)
  RETURN SYS_REFCURSOR
  IS    rc SYS_REFCURSOR;
  BEGIN    IF p_mode = 'FULL' THENOPEN rc FORSELECT          v.COD_AQUISICAO,
          v.USUARIO,
          v.DEPTO_REMETENTE,
          v.DEPTO_DESTINATARIO,
          v.DT_ENTRADA,
          CASEWHEN v.DT_SAIDA IS NULL AND p_close_open_intervals THEN p_cutoff_ts
            ELSE v.DT_SAIDA
          END AS DT_SAIDA,
          v.TEMPO_MICROTAREFA,
          v.DESC_MICRO_TAREFA
        FROM ORIGINAL.VW_MICROTAREFAS_ANALITICA v
        WHERE (v.DT_SAIDA IS NOT NULL OR p_close_open_intervals);
    ELSE-- INCR: considera apenas novos registros onde (COALESCE(DT_SAIDA, DT_ENTRADA) > watermark)OPEN rc FORSELECT          v.COD_AQUISICAO,
          v.USUARIO,
          v.DEPTO_REMETENTE,
          v.DEPTO_DESTINATARIO,
          v.DT_ENTRADA,
          CASEWHEN v.DT_SAIDA IS NULL AND p_close_open_intervals THEN p_cutoff_ts
            ELSE v.DT_SAIDA
          END AS DT_SAIDA,
          v.TEMPO_MICROTAREFA,
          v.DESC_MICRO_TAREFA
        FROM ORIGINAL.VW_MICROTAREFAS_ANALITICA v
        WHERE (NVL(v.DT_SAIDA, v.DT_ENTRADA) > p_wm)
          AND (v.DT_SAIDA IS NOT NULL OR p_close_open_intervals);
    END IF;
    RETURN rc;
  END;
  -------------------------------------------------------------------- Interno: insere (idempotente) na FATO usando UK natural--  - Calcula DIAS_UTEIS via FN_DIAS_UTEIS--  - Calcula VELOCIDADE_ATUAL = horas_atual - horas_anterior(na FATO)--  - Garante não inserir duplicado (UK + NOT EXISTS)------------------------------------------------------------------PROCEDURE LOAD_FATO(p_mode VARCHAR2,
                      p_wm   TIMESTAMP,
                      p_close_open_intervals BOOLEAN,
                      p_cutoff_ts TIMESTAMP)
  IS    rc     SYS_REFCURSOR;
    v_row  ORIGINAL.VW_MICROTAREFAS_ANALITICA%ROWTYPE; -- só para tipos-- variáveis locais    l_cod_aquisicao      NUMBER;
    l_usuario            VARCHAR2(255);
    l_depto_remetente    VARCHAR2(255);
    l_depto_destinatario VARCHAR2(255);
    l_dt_entrada         TIMESTAMP;
    l_dt_saida           TIMESTAMP;
    l_itv                INTERVAL DAY TO SECOND;
    l_desc               VARCHAR2(4000);
    l_dias_uteis         NUMBER;
    l_horas_atual        NUMBER;
    l_horas_prev         NUMBER;
  BEGIN    rc := SRC_DATA(p_mode, p_wm, p_close_open_intervals, p_cutoff_ts);
    LOOP
      FETCH rc INTO l_cod_aquisicao, l_usuario, l_depto_remetente, l_depto_destinatario,
                     l_dt_entrada, l_dt_saida, l_itv, l_desc;
      EXIT WHEN rc%NOTFOUND;
      -- calcula métricas      l_dias_uteis  := ORIGINAL.FN_DIAS_UTEIS(l_dt_entrada, l_dt_saida);
      l_horas_atual := ORIGINAL.FN_INTERVAL_TO_HOURS(l_itv);
      -- busca horas anteriores no último registro já inserido para o mesmo COD_AQUISICAOSELECT ORIGINAL.FN_INTERVAL_TO_HOURS(TEMPO_MICROTAREFA)
        INTO l_horas_prev
        FROM (
          SELECT TEMPO_MICROTAREFA
            FROM ORIGINAL.FATO_MICROTAREFAS
           WHERE COD_AQUISICAO = l_cod_aquisicao
             AND DT_ENTRADA < l_dt_entrada
           ORDER BY DT_ENTRADA DESC        )
       WHERE ROWNUM = 1      ;
      EXCEPTION WHEN NO_DATA_FOUND THEN        l_horas_prev := NULL;
      -- idempotência: só insere se não existir a combinação naturalINSERT /*+ APPEND_VALUES */ INTO ORIGINAL.FATO_MICROTAREFAS (
        COD_AQUISICAO, USUARIO, DEPTO_REMETENTE, DEPTO_DESTINATARIO,
        DT_ENTRADA, DT_SAIDA, TEMPO_MICROTAREFA, DIAS_UTEIS, VELOCIDADE_ATUAL,
        DESC_MICRO_TAREFA, DT_ATUALIZACAO
      )
      SELECT        l_cod_aquisicao, l_usuario, l_depto_remetente, l_depto_destinatario,
        l_dt_entrada, l_dt_saida, l_itv, l_dias_uteis,
        CASE WHEN l_horas_prev IS NULL THEN NULL ELSE (l_horas_atual - l_horas_prev) END,
        l_desc, SYSTIMESTAMP
      FROM DUAL
      WHERE NOT EXISTS (
        SELECT 1 FROM ORIGINAL.FATO_MICROTAREFAS f
         WHERE f.COD_AQUISICAO   = l_cod_aquisicao
           AND f.DT_ENTRADA      = l_dt_entrada
           AND f.DT_SAIDA        = l_dt_saida
      );
    END LOOP;
    CLOSE rc;
    COMMIT;
  END;
