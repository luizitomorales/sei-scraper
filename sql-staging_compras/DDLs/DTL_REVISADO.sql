CREATE OR REPLACE PROCEDURE ORIGINAL.PRC_ATUALIZA_FATO_MICROTAREFAS AS BEGIN-- Limpeza total (opcional)DELETE FROM ORIGINAL.FATO_MICROTAREFAS;
