CREATE OR REPLACE PACKAGE ORIGINAL.PKG_FATO_MICROTAREFAS ASPROCEDURE RUN_FULL(p_close_open_intervals BOOLEAN DEFAULT FALSE,
                     p_cutoff_ts           TIMESTAMP DEFAULT SYSTIMESTAMP);
