-- Tabela principal de aquisição
CREATE TABLE MEC_AQUISICAO (
    COD_AQUISICAO NUMBER PRIMARY KEY,
    NUM_PROCESSO_SEI VARCHAR2(20 CHAR) NOT NULL,
    DESCRICAO VARCHAR2(4000 CHAR),
    DT_CRIACAO TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- Tabela de tarefas (macrotarefas)
CREATE TABLE MEC_TAREFA (
    ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    COD_AQUISICAO NUMBER NOT NULL,
    NOME_ANALISTA VARCHAR2(255 CHAR),
    DESC_TAREFA VARCHAR2(255 CHAR),
    DT_ENTRADA TIMESTAMP,
    DT_SAIDA TIMESTAMP,
    DESTINO VARCHAR2(255 CHAR),
    NUM_PROCESSO_SEI VARCHAR2(20 CHAR),
    DT_ENTRADA_DLOG TIMESTAMP,
    DT_INSTAURA_PROC TIMESTAMP,
    FUND_LEGAL VARCHAR2(255 CHAR),
    CREATED TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CREATED_BY VARCHAR2(255 CHAR),
    UPDATED TIMESTAMP,
    UPDATED_BY VARCHAR2(255 CHAR),
    FOREIGN KEY (COD_AQUISICAO) REFERENCES MEC_AQUISICAO(COD_AQUISICAO)
);

-- Tabela de mapeamento de descrições para macrotarefas
CREATE TABLE MEC_TAREFA_MAP (
    ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    PADRAO_DESCRICAO VARCHAR2(4000 CHAR) NOT NULL,
    MACRO_TAREFA VARCHAR2(255 CHAR) NOT NULL
);

-- Tabela de histórico
CREATE TABLE MEC_HISTORY (
    ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    TABLE_NAME VARCHAR2(128 CHAR),
    COLUMN_NAME VARCHAR2(128 CHAR),
    ACTION VARCHAR2(1 CHAR),
    ACTION_DATE TIMESTAMP,
    ACTION_BY VARCHAR2(255 CHAR),
    DATA_TYPE VARCHAR2(255 CHAR),
    TAB_ROW_VERSION NUMBER,
    OLD_VC VARCHAR2(4000 CHAR),
    NEW_VC VARCHAR2(4000 CHAR),
    OLD_NUMBER NUMBER,
    NEW_NUMBER NUMBER,
    OLD_DATE TIMESTAMP,
    NEW_DATE TIMESTAMP,
    OLD_CLOB CLOB,
    NEW_CLOB CLOB,
    OLD_BLOB BLOB,
    NUM_PROCEXEC VARCHAR2(20 CHAR),
    NUM_ARP VARCHAR2(255 CHAR),
    AREA_DEMANDANTE VARCHAR2(255 CHAR),
    NUM_PORTARIA VARCHAR2(255 CHAR),
    SIGLA VARCHAR2(255 CHAR),
    NUM_DFD VARCHAR2(255 CHAR),
    PCA VARCHAR2(10 CHAR),
    DT_VIG_INIC_ARP TIMESTAMP,
    DT_VIG_FINAL_ARP TIMESTAMP,
    NUM_CONTRAT_PCA VARCHAR2(255 CHAR),
    ETAPA_PROC_EXEC VARCHAR2(255 CHAR),
    MODALIDADE VARCHAR2(255 CHAR),
    CREATED TIMESTAMP,
    CREATED_BY VARCHAR2(255 CHAR),
    UPDATED TIMESTAMP,
    UPDATED_BY VARCHAR2(255 CHAR)
);

-- Tabela de staging para dados do SEI/MS
CREATE TABLE STG_MOVIMENTACAO_PROCESSO (
    ID_MOVIMENTACAO NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    NUM_PROCESSO_SEI VARCHAR2(20 CHAR) NOT NULL,
    DT_MOVIMENTACAO TIMESTAMP NOT NULL,
    USUARIO VARCHAR2(255 CHAR),
    DESCRICAO VARCHAR2(4000 CHAR),
    DEPTO_REMETENTE VARCHAR2(255 CHAR),
    DEPTO_DESTINATARIO VARCHAR2(255 CHAR),
    DT_CARGA TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- Tabela resolvida com vínculo à aquisição
CREATE TABLE MOVIMENTACAO_RESOLVIDA (
    ID_MOVIMENTACAO NUMBER PRIMARY KEY,
    COD_AQUISICAO NUMBER NOT NULL,
    DT_MOVIMENTACAO TIMESTAMP NOT NULL,
    USUARIO VARCHAR2(255 CHAR),
    DESCRICAO VARCHAR2(4000 CHAR),
    DEPTO_REMETENTE VARCHAR2(255 CHAR),
    DEPTO_DESTINATARIO VARCHAR2(255 CHAR),
    DT_RESOLUCAO TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (COD_AQUISICAO) REFERENCES MEC_AQUISICAO(COD_AQUISICAO)
);

-- View que resolve o vínculo entre processo e aquisição
CREATE OR REPLACE VIEW VW_RESOLVE_MOVIMENTACAO AS
SELECT
    stg.ID_MOVIMENTACAO,
    aq.COD_AQUISICAO,
    stg.DT_MOVIMENTACAO,
    stg.USUARIO,
    stg.DESCRICAO,
    stg.DEPTO_REMETENTE,
    stg.DEPTO_DESTINATARIO,
    stg.DT_CARGA
FROM STG_MOVIMENTACAO_PROCESSO stg
JOIN MEC_AQUISICAO aq ON stg.NUM_PROCESSO_SEI = aq.NUM_PROCESSO_SEI;

-- Procedure que carrega MEC_TAREFA com base na movimentação resolvida
CREATE OR REPLACE PROCEDURE PRC_CARGA_MEC_TAREFA AS
BEGIN
    INSERT INTO MEC_TAREFA (
        COD_AQUISICAO,
        NOME_ANALISTA,
        DESC_TAREFA,
        DT_ENTRADA,
        DESTINO,
        NUM_PROCESSO_SEI
    )
    SELECT
        r.COD_AQUISICAO,
        CASE WHEN r.USUARIO IS NOT NULL THEN r.USUARIO ELSE 'SEM ANALISTA' END,
        m.MACRO_TAREFA,
        r.DT_MOVIMENTACAO,
        r.DEPTO_DESTINATARIO,
        a.NUM_PROCESSO_SEI
    FROM MOVIMENTACAO_RESOLVIDA r
    JOIN MEC_AQUISICAO a ON r.COD_AQUISICAO = a.COD_AQUISICAO
    JOIN MEC_TAREFA_MAP m ON LOWER(r.DESCRICAO) LIKE LOWER('%' || m.PADRAO_DESCRICAO || '%');
END;

