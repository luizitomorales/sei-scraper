-- 6. View de resolução: VW_RESOLVE_MOVIMENTACAO
CREATE OR REPLACE VIEW VW_RESOLVE_MOVIMENTACAO AS
SELECT
    S.NUM_PROCESSO_SEI,
    S.DT_MOVIMENTACAO,
    S.DESCRICAO,
    S.DEPTO_REMETENTE,
    S.DEPTO_DESTINATARIO,
    A.COD_AQUISICAO,
    M.ID AS ID_MAP,
    M.MACRO_TAREFA,
    R.ANALISTA,
    R.AREA_DESTINO,
    R.ETAPA_PROC_AQUI
FROM STG_MOVIMENTACAO_PROCESSO S
JOIN MEC_AQUISICAO A ON S.NUM_PROCESSO_SEI = A.NUM_PROCESSO_SEI
LEFT JOIN MEC_TAREFA_MAP M ON LOWER(S.DESCRICAO) LIKE '%' || LOWER(M.PADRAO_DESCRICAO) || '%'
LEFT JOIN MEC_ANALI_RESP R ON A.COD_AQUISICAO = R.COD_AQUISICAO
WHERE M.ATIVO = 'S';

-- 7. Procedure de carga: PRC_CARGA_DESEMPENHO
CREATE OR REPLACE PROCEDURE PRC_CARGA_MEC_TAREFA IS
BEGIN
    FOR R IN (
        SELECT * FROM VW_RESOLVE_MOVIMENTACAO
        WHERE NOT EXISTS (
            SELECT 1 FROM MEC_TAREFA
            WHERE NUM_PROCESSO_SEI = R.NUM_PROCESSO_SEI
              AND DT_ENTRADA = R.DT_MOVIMENTACAO
        )
    ) LOOP
        INSERT INTO MEC_TAREFA (
            COD_AQUISICAO,
            NUM_PROCESSO_SEI,
            DESC_TAREFA,
            NOME_ANALISTA,
            DT_ENTRADA,
            DESTINO,
            ID_MAP
        ) VALUES (
            R.COD_AQUISICAO,
            R.NUM_PROCESSO_SEI,
            R.DESCRICAO,
            NVL(R.ANALISTA, 'SEM ANALISTA'),
            R.DT_MOVIMENTACAO,
            R.DEPTO_DESTINATARIO,
            R.ID_MAP
        );
    END LOOP;
    COMMIT;
END;