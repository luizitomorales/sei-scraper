-- 1. Tabela principal: MEC_AQUISICAO
CREATE TABLE MEC_AQUISICAO (
    COD_AQUISICAO NUMBER PRIMARY KEY,
    NUM_PROCESSO_SEI VARCHAR2(50) NOT NULL,
    TIPO_AQUISICAO VARCHAR2(100),
    DT_CADASTRO DATE,
    RESPONSAVEL VARCHAR2(100)
);

-- 2. Tabela de tarefas: MEC_TAREFA
CREATE TABLE MEC_TAREFA (
    ID_TAREFA NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    COD_AQUISICAO NUMBER NOT NULL,
    NUM_PROCESSO_SEI VARCHAR2(50),
    DESC_TAREFA VARCHAR2(4000),
    NOME_ANALISTA VARCHAR2(100),
    DT_ENTRADA DATE,
    DT_SAIDA DATE,
    DESTINO VARCHAR2(100),
    ID_MAP NUMBER,
    CONSTRAINT FK_TAREFA_AQUISICAO FOREIGN KEY (COD_AQUISICAO)
