-- 1. Tabela de Staging: Recebe dados brutos da movimentação externa
CREATE TABLE STG_MOVIMENTACAO_PROCESSO (
    ID_MOVIMENTACAO NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    NUM_PROCESSO_SEI VARCHAR2(20 CHAR) NOT NULL,
    DT_MOVIMENTACAO TIMESTAMP NOT NULL,
    USUARIO VARCHAR2(255 CHAR),
    DESCRICAO VARCHAR2(4000 CHAR),
    DEPTO_REMETENTE VARCHAR2(255 CHAR),
    DEPTO_DESTINATARIO VARCHAR2(255 CHAR),
    DT_CARGA TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- 2. Tabela Resolvida: Dados prontos para alimentar tabelas de desempenho
CREATE TABLE MOVIMENTACAO_RESOLVIDA (
    ID_MOVIMENTACAO NUMBER PRIMARY KEY,
    COD_AQUISICAO NUMBER NOT NULL,
    DT_MOVIMENTACAO TIMESTAMP NOT NULL,
    USUARIO VARCHAR2(255 CHAR),
    DESCRICAO VARCHAR2(4000 CHAR),
    DEPTO_REMETENTE VARCHAR2(255 CHAR),
    DEPTO_DESTINATARIO VARCHAR2(255 CHAR),
    DT_RESOLUCAO TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (COD_AQUISICAO) REFERENCES MEC_AQUISICAO(COD_AQUISICAO)
);

-- 3. View de Resolução: Une a staging com MEC_AQUISICAO via NUM_PROCESSO_SEI
CREATE OR REPLACE VIEW VW_RESOLVE_MOVIMENTACAO AS
SELECT
    stg.ID_MOVIMENTACAO,
    aq.COD_AQUISICAO,
    stg.DT_MOVIMENTACAO,
    stg.USUARIO,
    stg.DESCRICAO,
    stg.DEPTO_REMETENTE,
    stg.DEPTO_DESTINATARIO,
    stg.DT_CARGA
FROM STG_MOVIMENTACAO_PROCESSO stg
JOIN MEC_AQUISICAO aq
    ON stg.NUM_PROCESSO_SEI = aq.NUM_PROCESSO_SEI;

-- 4. Procedure de Carga: Insere dados resolvidos na tabela final
CREATE OR REPLACE PROCEDURE PRC_RESOLVE_MOVIMENTACAO AS
BEGIN
    INSERT INTO MOVIMENTACAO_RESOLVIDA (
        ID_MOVIMENTACAO,
        COD_AQUISICAO,
        DT_MOVIMENTACAO,
        USUARIO,
        DESCRICAO,
        DEPTO_REMETENTE,
        DEPTO_DESTINATARIO
    )
    SELECT
        ID_MOVIMENTACAO,
        COD_AQUISICAO,
        DT_MOVIMENTACAO,
        USUARIO,
        DESCRICAO,
        DEPT0_REMETENTE,
        DEPTO_DESTINATARIO
    FROM VW_RESOLVE_MOVIMENTACAO;
END;